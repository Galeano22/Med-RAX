"""MedRax-ReportToPacs: turn a medical report (markdown, with images) into a
PDF, encapsulate it in a DICOM Encapsulated PDF object using the patient's
information, and STOW-RS it back to the DICOMweb server.

Typical flow:
  1. The agent retrieves a study with MedRax-Dicomweb and analyzes the images
     (classifier, segmentation, grounding, ... producing overlay PNGs).
  2. The user asks to "create a report and send it to PACS".
  3. This tool renders the markdown report -- including any overlay/segmentation
     images -- as a PDF, wraps it in a DICOM object carrying the patient/study
     identifiers (so it lands in the SAME study), and stores it via STOW-RS.

The report becomes a new series (Modality "DOC") inside the existing study, so
it shows up alongside the images in any DICOM viewer (e.g. OHIF).
"""

import io
import os
import tempfile
from datetime import datetime
from typing import Dict, List, Optional, Tuple, Type

import requests
from markdown_pdf import MarkdownPdf, Section
from pydicom.dataset import FileDataset, FileMetaDataset
from pydicom.uid import ExplicitVRLittleEndian, generate_uid, PYDICOM_IMPLEMENTATION_UID
from pydantic import BaseModel, Field
from langchain_core.callbacks import AsyncCallbackManagerForToolRun, CallbackManagerForToolRun
from langchain_core.tools import BaseTool

from .dicomweb import _DicomWebClient, _clean, _tag_value, _TAG

# SOP Class UID for Encapsulated PDF Storage.
_ENCAPSULATED_PDF_SOP_CLASS = "1.2.840.10008.5.1.4.1.1.104.1"

# Study/patient fields we want when looking the study up.
_REPORT_FIELDS = [
    _TAG["StudyInstanceUID"],
    _TAG["PatientName"],
    _TAG["PatientID"],
    _TAG["AccessionNumber"],
    _TAG["StudyDate"],
    _TAG["StudyTime"],
    _TAG["StudyDescription"],
    "00100030",  # PatientBirthDate
    "00100040",  # PatientSex
    "00200010",  # StudyID
]


def _render_pdf(
    title: str,
    report_text: str,
    header: Dict[str, Optional[str]],
    image_paths: Optional[List[str]] = None,
) -> bytes:
    """Render a markdown report (with embedded images) to PDF bytes.

    report_text is treated as markdown. Any images in image_paths that exist on
    disk are embedded in an "Images" section (segmentation/grounding overlays).
    """
    lines: List[str] = [f"# {title}", ""]
    header_lines = [f"**{label}:** {value}  " for label, value in header.items() if value]
    if header_lines:
        lines += header_lines + [""]
    lines += ["---", "", report_text or "", ""]

    # Resolve to absolute paths: markdown images are embedded with root="/", so a
    # relative path (e.g. "temp/seg.png") would be looked up under "/temp/..." and
    # silently skipped. abspath() makes it work regardless of the caller's CWD.
    valid_images = [os.path.abspath(p) for p in (image_paths or []) if p and os.path.isfile(p)]
    if valid_images:
        lines += ["## Images", ""]
        for path in valid_images:
            lines += [f"![{os.path.basename(path)}]({path})", ""]

    lines += [
        "---",
        "",
        "*Generated by MedRAX AI. This report is AI-assisted and must be reviewed "
        "and approved by a qualified physician before clinical use.*",
    ]
    markdown = "\n".join(lines)

    pdf = MarkdownPdf(toc_level=0)
    # root="/" lets us reference images by absolute path from any directory.
    pdf.add_section(Section(markdown, root="/"))
    pdf.meta["title"] = title

    # MarkdownPdf.save writes to a path; render to a temp file then read bytes.
    tmp_path = tempfile.NamedTemporaryFile(suffix=".pdf", delete=False).name
    try:
        pdf.save(tmp_path)
        with open(tmp_path, "rb") as fh:
            return fh.read()
    finally:
        try:
            os.remove(tmp_path)
        except OSError:
            pass


def _build_encapsulated_pdf(
    pdf_bytes: bytes, meta: Dict[str, Optional[str]], title: str
) -> Tuple[bytes, str, str]:
    """Wrap PDF bytes in a DICOM Encapsulated PDF instance.

    Returns (dicom_bytes, sop_instance_uid, series_instance_uid).
    """
    now = datetime.now()
    sop_instance_uid = generate_uid()
    series_instance_uid = generate_uid()

    file_meta = FileMetaDataset()
    file_meta.MediaStorageSOPClassUID = _ENCAPSULATED_PDF_SOP_CLASS
    file_meta.MediaStorageSOPInstanceUID = sop_instance_uid
    file_meta.TransferSyntaxUID = ExplicitVRLittleEndian
    file_meta.ImplementationClassUID = PYDICOM_IMPLEMENTATION_UID

    ds = FileDataset(None, {}, file_meta=file_meta, preamble=b"\x00" * 128)
    ds.SpecificCharacterSet = "ISO_IR 192"  # UTF-8

    # Patient module
    ds.PatientName = meta.get("patient_name") or "ANONYMOUS"
    ds.PatientID = meta.get("patient_id") or ""
    ds.PatientBirthDate = meta.get("birth_date") or ""
    ds.PatientSex = meta.get("sex") or ""

    # General Study module - reuse the existing study so the report is linked to it.
    ds.StudyInstanceUID = meta.get("study_instance_uid") or generate_uid()
    ds.StudyDate = meta.get("study_date") or now.strftime("%Y%m%d")
    ds.StudyTime = meta.get("study_time") or now.strftime("%H%M%S")
    ds.AccessionNumber = meta.get("accession_number") or ""
    ds.StudyID = meta.get("study_id") or ""
    ds.ReferringPhysicianName = ""

    # Encapsulated Document Series module - a new DOC series.
    ds.Modality = "DOC"
    ds.SeriesInstanceUID = series_instance_uid
    ds.SeriesNumber = "999"
    ds.SeriesDescription = title

    # SOP Common + Encapsulated Document module
    ds.SOPClassUID = _ENCAPSULATED_PDF_SOP_CLASS
    ds.SOPInstanceUID = sop_instance_uid
    ds.InstanceNumber = "1"
    ds.ContentDate = now.strftime("%Y%m%d")
    ds.ContentTime = now.strftime("%H%M%S")
    ds.BurnedInAnnotation = "NO"
    ds.ConversionType = "SD"  # Synthesized / scanned document
    ds.DocumentTitle = title
    ds.MIMETypeOfEncapsulatedDocument = "application/pdf"

    # EncapsulatedDocument (OB) must be even length.
    if len(pdf_bytes) % 2:
        pdf_bytes += b"\x00"
    ds.EncapsulatedDocument = pdf_bytes

    buffer = io.BytesIO()
    ds.save_as(buffer, enforce_file_format=True)
    return buffer.getvalue(), sop_instance_uid, series_instance_uid


class MedRAXReportToPacsInput(BaseModel):
    """Input schema for the MedRax-ReportToPacs tool."""

    report_text: str = Field(
        ...,
        description="The full medical report / findings text, in markdown "
        "(headings, bold, bullet lists are supported).",
    )
    title: str = Field("AI Radiology Report", description="Title/heading of the report document.")
    image_paths: Optional[List[str]] = Field(
        None,
        description="Optional list of image file paths to embed in the report, e.g. the "
        "segmentation or grounding overlay PNGs produced by the analysis tools.",
    )
    study_instance_uid: Optional[str] = Field(
        None,
        description="StudyInstanceUID of the study the report belongs to (from MedRax-Dicomweb "
        "retrieve_study). Strongly preferred so the report is attached to the correct study.",
    )
    accession_number: Optional[str] = Field(
        None, description="Accession number of the study, used to look it up if no UID is given."
    )
    patient_name: Optional[str] = Field(
        None,
        description="Patient name. Used to look up the study if no UID/accession is given, or as "
        "the patient identity if the study cannot be found on the server.",
    )
    patient_id: Optional[str] = Field(
        None, description="Patient ID, used as a fallback when the study is not found on the server."
    )
    dicomweb_url: Optional[str] = Field(
        None,
        description="Optional. DICOMweb server to send to; defaults to the configured server "
        "(the one studies are retrieved from).",
    )
    username: Optional[str] = Field(None, description="Optional. Username for an overridden server.")
    password: Optional[str] = Field(None, description="Optional. Password for an overridden server.")


class MedRAXReportToPacsTool(BaseTool):
    """Create a medical report PDF (markdown + images), encapsulate it in DICOM, STOW-RS to PACS."""

    name: str = "MedRax-ReportToPacs"
    description: str = (
        "Creates a medical report as a PDF, encapsulates it in a DICOM Encapsulated PDF object "
        "using the patient's information, and sends it to the DICOMweb server (PACS) via STOW-RS. "
        "Use this when the user asks to create/write a report and send/store/upload it to PACS. "
        "report_text is markdown; pass image_paths to embed overlay/segmentation images produced "
        "by the analysis tools. Provide study_instance_uid (from MedRax-Dicomweb retrieve_study) so "
        "the report is filed in the same study as the images. Defaults to the configured server; "
        "pass dicomweb_url to target another one."
    )
    args_schema: Type[BaseModel] = MedRAXReportToPacsInput

    base_url: str = "http://localhost:8042/dicom-web"
    username: Optional[str] = None
    password: Optional[str] = None
    timeout: int = 60

    def __init__(
        self,
        base_url: str = "http://localhost:8042/dicom-web",
        username: Optional[str] = None,
        password: Optional[str] = None,
        timeout: int = 60,
    ):
        """Initialize with the default DICOMweb server (same one used for retrieval)."""
        super().__init__()
        self.base_url = base_url
        self.username = username or None
        self.password = password or None
        self.timeout = timeout

    def _client(self, url, user, pw) -> _DicomWebClient:
        url, user, pw = _clean(url), _clean(user), _clean(pw)
        if url:
            return _DicomWebClient(url, user, pw, timeout=self.timeout)
        return _DicomWebClient(self.base_url, self.username, self.password, timeout=self.timeout)

    def _lookup_study(
        self,
        client: _DicomWebClient,
        study_instance_uid: Optional[str],
        accession_number: Optional[str],
        patient_name: Optional[str],
    ) -> Optional[Dict]:
        """Find the study on the server to reuse its patient/study identifiers."""
        base = {"includefield": _REPORT_FIELDS, "limit": 50}
        queries: List[Dict] = []
        if study_instance_uid:
            queries.append({**base, _TAG["StudyInstanceUID"]: study_instance_uid})
        if accession_number:
            queries.append({**base, _TAG["AccessionNumber"]: accession_number})
        if patient_name:
            pn = "*" + patient_name.replace(" ", "*") + "*"
            queries.append({**base, _TAG["PatientName"]: pn})
            queries.append({**base, _TAG["PatientName"]: pn.upper()})
        for params in queries:
            try:
                results = client.search_studies(params)
            except requests.RequestException:
                results = []
            if results:
                return results[0]
        return None

    def _run(
        self,
        report_text: str,
        title: str = "AI Radiology Report",
        image_paths: Optional[List[str]] = None,
        study_instance_uid: Optional[str] = None,
        accession_number: Optional[str] = None,
        patient_name: Optional[str] = None,
        patient_id: Optional[str] = None,
        dicomweb_url: Optional[str] = None,
        username: Optional[str] = None,
        password: Optional[str] = None,
        run_manager: Optional[CallbackManagerForToolRun] = None,
    ) -> Tuple[Dict, Dict]:
        """Render the report, encapsulate it as DICOM, and STOW-RS it to the server."""
        try:
            title = _clean(title) or "AI Radiology Report"
            study_instance_uid = _clean(study_instance_uid)
            accession_number = _clean(accession_number)
            patient_name = _clean(patient_name)
            patient_id = _clean(patient_id)
            image_paths = [_clean(p) for p in image_paths] if image_paths else []

            if not _clean(report_text):
                return ({"error": "report_text is empty; nothing to send."}, {"status": "failed"})

            client = self._client(dicomweb_url, username, password)

            # Resolve patient/study identifiers from the server when possible.
            study = self._lookup_study(client, study_instance_uid, accession_number, patient_name)
            linked = study is not None
            if linked:
                meta = {
                    "patient_name": _tag_value(study, _TAG["PatientName"], person_name=True),
                    "patient_id": _tag_value(study, _TAG["PatientID"]),
                    "birth_date": _tag_value(study, "00100030"),
                    "sex": _tag_value(study, "00100040"),
                    "study_instance_uid": _tag_value(study, _TAG["StudyInstanceUID"]),
                    "study_date": _tag_value(study, _TAG["StudyDate"]),
                    "study_time": _tag_value(study, _TAG["StudyTime"]),
                    "accession_number": _tag_value(study, _TAG["AccessionNumber"]),
                    "study_id": _tag_value(study, "00200010"),
                    "study_description": _tag_value(study, _TAG["StudyDescription"]),
                }
            else:
                # Study not found: use provided identity and a standalone new study.
                meta = {
                    "patient_name": patient_name,
                    "patient_id": patient_id,
                    "study_instance_uid": study_instance_uid,  # may be None -> new UID
                    "accession_number": accession_number,
                }

            header = {
                "Patient": meta.get("patient_name"),
                "Patient ID": meta.get("patient_id"),
                "Accession": meta.get("accession_number"),
                "Study": meta.get("study_description"),
                "Study date": meta.get("study_date"),
                "Report date": datetime.now().strftime("%Y-%m-%d %H:%M"),
            }

            pdf_bytes = _render_pdf(title, report_text, header, image_paths)
            dicom_bytes, sop_uid, series_uid = _build_encapsulated_pdf(pdf_bytes, meta, title)
            client.store_instances([dicom_bytes])

            output = {
                "status": "sent",
                "server": client.base_url,
                "linked_to_existing_study": linked,
                "patient_name": meta.get("patient_name"),
                "study_instance_uid": meta.get("study_instance_uid"),
                "series_instance_uid": series_uid,
                "sop_instance_uid": sop_uid,
                "images_embedded": len([p for p in image_paths if p and os.path.isfile(p)]),
                "pdf_bytes": len(pdf_bytes),
                "note": (
                    "Report encapsulated as a DICOM PDF (Modality DOC) and stored via STOW-RS. "
                    + (
                        "It is attached to the existing study and will appear alongside the images."
                        if linked
                        else "The study was not found on the server, so the report was stored as a "
                        "new standalone study with the provided patient identity."
                    )
                ),
            }
            metadata = {
                "action": "report_to_pacs",
                "status": "completed",
                "linked_to_existing_study": linked,
            }
            return output, metadata

        except requests.HTTPError as exc:
            resp = exc.response
            return (
                {"error": f"STOW-RS failed ({resp.status_code if resp is not None else ''}): {exc}"},
                {"action": "report_to_pacs", "status": "failed", "error_details": str(exc)},
            )
        except requests.RequestException as exc:
            return (
                {"error": f"Could not reach DICOMweb server: {exc}"},
                {"action": "report_to_pacs", "status": "failed", "error_details": str(exc)},
            )
        except Exception as exc:
            return (
                {"error": str(exc)},
                {"action": "report_to_pacs", "status": "failed", "error_details": str(exc)},
            )

    async def _arun(
        self,
        report_text: str,
        title: str = "AI Radiology Report",
        image_paths: Optional[List[str]] = None,
        study_instance_uid: Optional[str] = None,
        accession_number: Optional[str] = None,
        patient_name: Optional[str] = None,
        patient_id: Optional[str] = None,
        dicomweb_url: Optional[str] = None,
        username: Optional[str] = None,
        password: Optional[str] = None,
        run_manager: Optional[AsyncCallbackManagerForToolRun] = None,
    ) -> Tuple[Dict, Dict]:
        """Async version of _run."""
        return self._run(
            report_text,
            title,
            image_paths,
            study_instance_uid,
            accession_number,
            patient_name,
            patient_id,
            dicomweb_url,
            username,
            password,
        )
